// The token radar's model, version radar-2: one snapshot of the protocol universe in, one ranked
// board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and every
// other rankable pre-token protocol in the snapshot, at any TVL: the early rows the radar exists to
// find. A protocol is pre-token when its record carries no token (no market cap, no CoinGecko id, no
// symbol); rankable also excludes the wrapped, staked and bridged products and exchanges the
// watchlist rule itself excludes, at any TVL. The snapshot's live-token protocols are never ranked.
// They are the model's teachers and the dashboard's comparison set, shown with the market's own values.
//
// Implied value follows only from the snapshot's own figures, in three parts:
//
//   peer multiple  Live protocols in the snapshot trade at a market cap per dollar of TVL. For a
//                  pre-token protocol's category, the multiple is the median market-cap / TVL of
//                  the live protocols in that same category, shrunk toward the global median by
//                  the peer count (weight n / (n + 4)) and clamped to [0.1, 4]. A category with
//                  fewer than three live peers uses the global median on its own. No hand-set
//                  multiple and no protocol name is ever special-cased.
//   growth         = clamp(change_7d, -60, 120) per cent; multiplier 1 + (growth / 100) x 0.5.
//   maturity       = 0.6 + min(age_days, 1095) / 1095 x 0.4, age from listed_at to the snapshot's
//                  as_of day; an unknown age counts as 365 days.
//   implied        = max(1, round(tvl_usd x peer multiple x growth multiplier x maturity))
//
// The dashboard recomputes every row from the same figures, so the page and board.json visibly agree.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's tunable constants: everything except the peer multiples, which the snapshot sets. */
export interface ModelConstants {
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  multiple_floor: number;
  multiple_cap: number;
  peer_min_peers: number;
  peer_shrink_peers: number;
}

export const MODEL: ModelConstants = {
  growth_weight: 0.5,
  growth_floor: -60,
  growth_cap: 120,
  maturity_floor: 0.6,
  maturity_range: 0.4,
  maturity_days: 1095,
  unknown_age_days: 365,
  multiple_floor: 0.1,
  multiple_cap: 4,
  peer_min_peers: 3,
  peer_shrink_peers: 4,
};

